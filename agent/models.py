from pydantic import BaseModel, Field

class ContextRelevance(BaseModel):
    relevance_score: int = Field(description="Retrieved context relevance on a scale of 1 to 5")
    reason: str = Field(description="A concise sentence explaining the reasoning behind the relevance score")

class RAGAnswer(BaseModel):
    answer: str = Field(description="The response generated by the LLM based on the question and context provided to it")